# Columns actually used by the app's schema (0-indexed into the 28-col rows).
ANNUAL_IDX = [0, 1, 2, 3, 4, 20]          # -> ANNUAL_FYS, in order
MONTH_IDX = {"2026-04": 22, "2026-05": 23, "2026-06": 24, "2026-07": 26}
TILL_MONTH_IDX = 27                       # only meaningful for report_month 2026-07
TOTAL_CHECK_TOLERANCE = 3                 # PDF rounds each cell independently


def self_validate():
    """VARIABLE + FIXED should equal TOTAL (within rounding) for every
    column actually used below — catches transcription typos before they
    ever reach the DB."""
    problems = []
    for product, blocks in DATA.items():
        for plant in PLANTS:
            total_row = blocks["TOTAL"][plant]
            var_row = blocks["VARIABLE"][plant]
            fix_row = blocks["FIXED"][plant]
            for idx in ANNUAL_IDX + list(MONTH_IDX.values()) + [TILL_MONTH_IDX]:
                t, v, f = total_row[idx], var_row[idx], fix_row[idx]
                if abs((v + f) - t) > TOTAL_CHECK_TOLERANCE:
                    problems.append(f"{product}/{plant} col{idx}: V({v})+F({f})={v+f} vs T({t})")
    return problems


def build_annual_entries():
    """{fy: {product: [ {cost_type, plant, value}, ... ]}}"""
    out = {fy: {} for fy in ANNUAL_FYS}
    for product, blocks in DATA.items():
        for fy_i, fy in enumerate(ANNUAL_FYS):
            entries = []
            for cost_type in ("VARIABLE", "FIXED"):
                for plant in PLANTS:
                    value = blocks[cost_type][plant][ANNUAL_IDX[fy_i]]
                    entries.append({"cost_type": cost_type, "plant": plant, "value": float(value)})
            out[fy][product] = entries
    return out


def build_monthly_entries():
    """{report_month: {product: [ {cost_type, plant, month_value, till_month_value}, ... ]}}"""
    out = {rm: {} for rm in MONTH_IDX}
    for product, blocks in DATA.items():
        for rm, idx in MONTH_IDX.items():
            entries = []
            for cost_type in ("VARIABLE", "FIXED"):
                for plant in PLANTS:
                    month_value = float(blocks[cost_type][plant][idx])
                    till_month_value = float(blocks[cost_type][plant][TILL_MONTH_IDX]) if rm == "2026-07" else None
                    entries.append({
                        "cost_type": cost_type, "plant": plant,
                        "month_value": month_value, "till_month_value": till_month_value,
                    })
            out[rm][product] = entries
    return out


def diff_annual(apply: bool):
    entries_by_fy = build_annual_entries()
    changed = 0
    for fy, by_product in entries_by_fy.items():
        for product, entries in by_product.items():
            current = db.get_cost_trend_annual(product, [fy])[fy]
            for e in entries:
                cur_val = current.get(e["cost_type"], {}).get(e["plant"])
                new_val = e["value"]
                if cur_val is None or abs(cur_val - new_val) > 0.01:
                    print(f"  ANNUAL {fy} {product} {e['cost_type']:>8} {e['plant']:>4}: "
                          f"{cur_val!r} -> {new_val}")
                    changed += 1
            if apply:
                db.save_cost_trend_annual(fy, product, entries)
    print(f"Annual: {changed} cell(s) changed" + (" (applied)" if apply else " (dry run)"))


def diff_monthly(apply: bool):
    entries_by_rm = build_monthly_entries()
    changed = 0
    for rm, by_product in entries_by_rm.items():
        for product, entries in by_product.items():
            current = db.get_cost_trend_monthly(product, [rm])[rm]
            for e in entries:
                cur = current.get(e["cost_type"], {}).get(e["plant"], {})
                cur_m, cur_t = cur.get("month"), cur.get("till_month")
                new_m, new_t = e["month_value"], e["till_month_value"]
                m_changed = cur_m is None or abs(cur_m - new_m) > 0.01
                t_changed = (new_t is not None) and (cur_t is None or abs(cur_t - new_t) > 0.01)
                if m_changed or t_changed:
                    print(f"  MONTHLY {rm} {product} {e['cost_type']:>8} {e['plant']:>4}: "
                          f"month {cur_m!r}->{new_m}"
                          + (f", till_month {cur_t!r}->{new_t}" if new_t is not None else ""))
                    changed += 1
            if apply:
                # Only overwrite till_month_value where we actually have a
                # PDF-sourced figure (report_month 2026-07) — a full-grid
                # save on 04/05/06 would otherwise NULL out any till_month
                # value already entered there.
                if rm == "2026-07":
                    db.save_cost_trend_monthly(rm, product, entries)
                else:
                    db.save_cost_trend_monthly_field(
                        rm, product,
                        [{"cost_type": e["cost_type"], "plant": e["plant"], "value": e["month_value"]} for e in entries],
                        "month_value",
                    )
    print(f"Monthly: {changed} cell(s) changed" + (" (applied)" if apply else " (dry run)"))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true", help="Write changes to the DB (default: dry run)")
    args = parser.parse_args()

    problems = self_validate()
    if problems:
        print(f"SELF-VALIDATION FAILED ({len(problems)} issue(s)) — aborting, fix transcription first:")
        for p in problems:
            print(" ", p)
        sys.exit(1)
    print("Self-validation OK (VARIABLE+FIXED matches TOTAL for all transcribed cells).\n")

    diff_annual(args.apply)
    diff_monthly(args.apply)
